/// Bir kademenin DPI kodu: X baytı, Y baytı (5000 üstü 100'lük adımlar) ve ×2 bayrağı (10000 üstü).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct DpiCode {
    pub x: u8,
    pub y: u8,
    pub double: bool,
}

pub fn encode(dpi: u32) -> DpiCode {
    let (target, double) = if dpi > 10_000 { ((dpi as f64 / 2.0).round() as u32, true) } else { (dpi, false) };
    if target > 5000 && target % 100 == 0 {
        let i = (target / 100 - 1) as usize;
        DpiCode { x: DPI_3311[i.min(219)], y: 1, double }
    } else {
        let i = (target.saturating_sub(50) / 50) as usize;
        DpiCode { x: DPI_3311[i.min(219)], y: 0, double }
    }
}

pub fn decode(code: DpiCode) -> u32 {
    // Tablonun ilk 200 değeri kesin artan; ters arama orada yapılır.
    let i = DPI_3311[..200].iter().position(|&b| b == code.x).unwrap_or(0) as u32;
    let base = if code.y == 1 { (i + 1) * 100 } else { (i + 1) * 50 };
    if code.double { base * 2 } else { base }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn factory_values() {
        for (dpi, x) in [(400, 0x09), (800, 0x12), (1600, 0x25), (3200, 0x4b), (4800, 0x70)] {
            assert_eq!(encode(dpi), DpiCode { x, y: 0, double: false }, "{dpi}");
            assert_eq!(decode(encode(dpi)), dpi);
        }
    }

    #[test]
    fn round_trip() {
        for dpi in (100..=12_000).step_by(50) {
            let d = decode(encode(dpi));
            // 5000 üstü 100'lük, 10000 üstü 200'lük adımlarla temsil edilir.
            let step = if dpi > 10_000 { 200 } else if dpi > 5000 { 100 } else { 50 };
            assert!(d.abs_diff(dpi) <= step, "{dpi} -> {d}");
        }
    }
}
